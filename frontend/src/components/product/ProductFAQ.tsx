export default function ProductFAQ({ slug }: { slug: string }) {
  const faqs = FAQS[slug]
  const [openIndex, setOpenIndex] = useState<number | null>(null)

  if (!faqs) return null

  return (
    <section className="max-w-3xl mx-auto px-4 sm:px-6 py-16">
      <div className="text-center mb-12">
        <span className="text-brand-gold font-bold tracking-[0.2em] uppercase text-xs mb-3 block">Got Questions?</span>
        <h2 className="text-3xl font-black text-brand-blue">الأسئلة الشائعة</h2>
      </div>

      <div className="space-y-3">
        {faqs.map((faq, i) => (
          <div key={i} className="bg-white rounded-2xl border border-brand-blue/5 shadow-sm overflow-hidden">
            <button
              onClick={() => setOpenIndex(openIndex === i ? null : i)}
              className="w-full flex items-center justify-between p-6 text-right hover:bg-brand-off-white/50 transition-colors"
            >
              <svg
                className={`w-5 h-5 text-brand-gold flex-shrink-0 transition-transform duration-300 ${openIndex === i ? 'rotate-180' : ''}`}
                fill="none"
                viewBox="0 0 24 24"
                stroke="currentColor"
                strokeWidth={2}
              >
                <path strokeLinecap="round" strokeLinejoin="round" d="M19 9l-7 7-7-7" />
              </svg>
              <span className="font-bold text-brand-blue text-sm md:text-base leading-snug flex-1 text-right mr-4">
                {faq.q}
              </span>
            </button>
            {openIndex === i && (
              <div className="px-6 pb-6">
                <p className="text-slate-500 text-sm leading-relaxed font-medium text-right border-t border-gray-100 pt-4">
                  {faq.a}
                </p>
              </div>
            )}
          </div>
        ))}
      </div>
    </section>
  )
}
